//! A tiny stroke font. Glyphs are polylines on a 4x6 grid (y grows downward),
//! so text is drawn with the same glowing beams as everything else.

type Glyph = &'static [&'static [(u8, u8)]];

pub const HEIGHT: f32 = 6.0;
pub const ADVANCE: f32 = 6.0;
const GLYPH_WIDTH: f32 = 4.0;

/// Width in pixels of `s` drawn with cap height `size`.
pub fn width(s: &str, size: f32) -> f32 {
    let n = s.chars().count() as f32;
    if n == 0.0 {
        return 0.0;
    }
    ((n - 1.0) * ADVANCE + GLYPH_WIDTH) * size / HEIGHT
}

pub fn glyph(c: char) -> Glyph {
    match c.to_ascii_uppercase() {
        'A' => &[&[(0, 6), (0, 2), (2, 0), (4, 2), (4, 6)], &[(0, 4), (4, 4)]],
        'B' => &[
            &[(0, 3), (3, 3), (4, 4), (4, 5), (3, 6), (0, 6), (0, 0), (3, 0), (4, 1), (4, 2), (3, 3)],
        ],
        'C' => &[&[(4, 1), (3, 0), (1, 0), (0, 1), (0, 5), (1, 6), (3, 6), (4, 5)]],
        'D' => &[&[(0, 0), (0, 6), (2, 6), (4, 4), (4, 2), (2, 0), (0, 0)]],
        'E' => &[&[(4, 0), (0, 0), (0, 6), (4, 6)], &[(0, 3), (3, 3)]],
        'F' => &[&[(4, 0), (0, 0), (0, 6)], &[(0, 3), (3, 3)]],
        'G' => &[&[(4, 1), (3, 0), (1, 0), (0, 1), (0, 5), (1, 6), (3, 6), (4, 5), (4, 3), (2, 3)]],
        'H' => &[&[(0, 0), (0, 6)], &[(4, 0), (4, 6)], &[(0, 3), (4, 3)]],
        'I' => &[&[(1, 0), (3, 0)], &[(2, 0), (2, 6)], &[(1, 6), (3, 6)]],
        'J' => &[&[(4, 0), (4, 5), (3, 6), (1, 6), (0, 5)]],
        'K' => &[&[(0, 0), (0, 6)], &[(4, 0), (0, 3), (4, 6)]],
        'L' => &[&[(0, 0), (0, 6), (4, 6)]],
        'M' => &[&[(0, 6), (0, 0), (2, 3), (4, 0), (4, 6)]],
        'N' => &[&[(0, 6), (0, 0), (4, 6), (4, 0)]],
        'O' => &[&[(1, 0), (3, 0), (4, 1), (4, 5), (3, 6), (1, 6), (0, 5), (0, 1), (1, 0)]],
        'P' => &[&[(0, 6), (0, 0), (3, 0), (4, 1), (4, 2), (3, 3), (0, 3)]],
        'Q' => &[
            &[(1, 0), (3, 0), (4, 1), (4, 5), (3, 6), (1, 6), (0, 5), (0, 1), (1, 0)],
            &[(2, 4), (4, 6)],
        ],
        'R' => &[&[(0, 6), (0, 0), (3, 0), (4, 1), (4, 2), (3, 3), (0, 3)], &[(2, 3), (4, 6)]],
        'S' => &[
            &[(4, 1), (3, 0), (1, 0), (0, 1), (0, 2), (1, 3), (3, 3), (4, 4), (4, 5), (3, 6), (1, 6), (0, 5)],
        ],
        'T' => &[&[(0, 0), (4, 0)], &[(2, 0), (2, 6)]],
        'U' => &[&[(0, 0), (0, 5), (1, 6), (3, 6), (4, 5), (4, 0)]],
        'V' => &[&[(0, 0), (2, 6), (4, 0)]],
        'W' => &[&[(0, 0), (1, 6), (2, 3), (3, 6), (4, 0)]],
        'X' => &[&[(0, 0), (4, 6)], &[(4, 0), (0, 6)]],
        'Y' => &[&[(0, 0), (2, 3), (4, 0)], &[(2, 3), (2, 6)]],
        'Z' => &[&[(0, 0), (4, 0), (0, 6), (4, 6)]],
        '0' => &[
            &[(1, 0), (3, 0), (4, 1), (4, 5), (3, 6), (1, 6), (0, 5), (0, 1), (1, 0)],
            &[(1, 5), (3, 1)],
        ],
        '1' => &[&[(1, 1), (2, 0), (2, 6)], &[(1, 6), (3, 6)]],
        '2' => &[&[(0, 1), (1, 0), (3, 0), (4, 1), (4, 2), (0, 6), (4, 6)]],
        '3' => &[&[(0, 0), (4, 0), (2, 3), (3, 3), (4, 4), (4, 5), (3, 6), (1, 6), (0, 5)]],
        '4' => &[&[(3, 6), (3, 0), (0, 4), (4, 4)]],
        '5' => &[&[(4, 0), (0, 0), (0, 3), (3, 3), (4, 4), (4, 5), (3, 6), (0, 6)]],
        '6' => &[&[(4, 0), (1, 0), (0, 1), (0, 5), (1, 6), (3, 6), (4, 5), (4, 4), (3, 3), (0, 3)]],
        '7' => &[&[(0, 0), (4, 0), (1, 6)]],
        '8' => &[
            &[
                (1, 3), (0, 2), (0, 1), (1, 0), (3, 0), (4, 1), (4, 2), (3, 3), (1, 3), (0, 4),
                (0, 5), (1, 6), (3, 6), (4, 5), (4, 4), (3, 3),
            ],
        ],
        '9' => &[&[(0, 6), (3, 6), (4, 5), (4, 1), (3, 0), (1, 0), (0, 1), (0, 2), (1, 3), (4, 3)]],
        ':' => &[&[(2, 1), (2, 2)], &[(2, 4), (2, 5)]],
        '.' => &[&[(2, 5), (2, 6)]],
        '-' => &[&[(1, 3), (3, 3)]],
        '+' => &[&[(0, 3), (4, 3)], &[(2, 1), (2, 5)]],
        '!' => &[&[(2, 0), (2, 4)], &[(2, 5), (2, 6)]],
        '/' => &[&[(0, 6), (4, 0)]],
        '>' => &[&[(1, 1), (3, 3), (1, 5)]],
        '<' => &[&[(3, 1), (1, 3), (3, 5)]],
        _ => &[],
    }
}
